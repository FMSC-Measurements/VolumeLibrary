inline double CV(double DBH, double HT, double A1, double A2) {
    return A1 + A2 * pow(DBH, 2.0) * HT;
}

inline double TRATIO(double DBH, double E1, double E2) {
    return E1 + E2 * pow(1.0 / (DBH - 3.0), 2.0);
}


