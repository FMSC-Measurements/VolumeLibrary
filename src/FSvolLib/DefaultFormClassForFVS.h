// --- Helper: normalize a 3-char FIA species code like Fortran CHARACTER*3 ---
// - Trims spaces
// - If it's digits and length <=3, left-pad zeros to width 3 (e.g., "17" -> "017")
// - If empty after trim -> "   " (three spaces)
// - Otherwise truncate to first 3 chars
static std::string normalizeSpec3(const std::string& spec) {
    // Trim
    auto l = spec.begin();
    auto r = spec.end();
    while (l != r && std::isspace(static_cast<unsigned char>(*l))) ++l;
    while (r != l && std::isspace(static_cast<unsigned char>(*(r - 1)))) --r;
    std::string s(l, r);
    if (s.empty()) return std::string(3, ' ');

    // Digits -> zero-pad left to 3
    if (std::all_of(s.begin(), s.end(),
        [](unsigned char c) { return std::isdigit(c); })) {
        if (s.size() < 3) return std::string(3 - s.size(), '0') + s;
        if (s.size() > 3) return s.substr(s.size() - 3); // keep last 3 digits
        return s;
    }

    // Non-digits: pad/truncate to 3
    if (s.size() < 3) return s + std::string(3 - s.size(), ' ');
    return s.substr(0, 3);
}

// --- Helper: find species index (1-based) in a fixed list; 0 if not found ---
template <std::size_t N>
static int findSpeciesIndex(const std::array<std::string, N>& list, const std::string& spec3) {
    for (std::size_t i = 0; i < N; ++i) {
        if (list[i] == spec3) return static_cast<int>(i) + 1; // 1-based
    }
    return 0;
}

// --- Helper: compute IFCDBH (1..5) from D (inches), matching Fortran ---
static int computeIfcdbh(double D) {
    int IFCDBH = static_cast<int>((D - 1.0) / 10.0) + 1;
    if (IFCDBH < 1) IFCDBH = 1;
    if (D > 40.9) IFCDBH = 5;
    if (IFCDBH > 5) IFCDBH = 5;
    return IFCDBH;
}

// --- Helper: parse species code from VOLEQ(8:10) as integer ---
// Fortran: SPEC = VOLEQ(8:10); if SPEC == "000" → FCLASS=80.
static std::string parseSpeciesFromVoleq(const std::string& VOLEQ) {
    // Ensure we can slice positions 8..10 (1-based) => index 7, length 3 in C++
    if (VOLEQ.size() < 10) {
        // If shorter, treat missing as spaces -> becomes 0
        return "000";
    }
    std::string spec3 = VOLEQ.substr(7, 3);
    return spec3;
}

