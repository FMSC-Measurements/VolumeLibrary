static int GetFormClass(const std::string& VOLEQ, int IFORST, double DBHOB)
{
    int FCLASS = 80;
    // Extract species code from VOLEQ(8:10)
    const std::string specCode = parseSpeciesFromVoleq(VOLEQ);

    // Special case: SPEC == "000"
    if (specCode == "000") {
        FCLASS = 80;
        return FCLASS;
    }

    // Dispatch to appropriate region function
    if (IFORST == 4 || IFORST == 7 || IFORST == 14 || IFORST == 16) {
        FCLASS = FORMCL_BM(specCode, IFORST, DBHOB);
    }
    else if (IFORST == 10 || IFORST == 11) {
        FCLASS = FORMCL_CA(specCode, IFORST, DBHOB);
    }
    else if (IFORST == 8 || IFORST == 17) {
        FCLASS = FORMCL_EC(specCode, IFORST, DBHOB);
    }
    else if (IFORST == 21) {
        FCLASS = FORMCL_NI(specCode, IFORST, DBHOB);
    }
    else if (IFORST == 12 || IFORST == 9) {
        FCLASS = FORMCL_PN(specCode, IFORST, DBHOB);
    }
    else if (IFORST == 1 || IFORST == 2 || IFORST == 20) {
        FCLASS = FORMCL_SO(specCode, IFORST, DBHOB);
    }
    else if (IFORST == 6 || IFORST == 15 || IFORST == 18 ||
        IFORST == 3 || IFORST == 5) {
        FCLASS = FORMCL_WC(specCode, IFORST, DBHOB);
    }
    return FCLASS;
}